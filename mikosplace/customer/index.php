}

function formatCurrency(amount) {
  return `&#8369;${parseFloat(amount || 0).toLocaleString('en-PH', { minimumFractionDigits: 2 })}`;
}

function esc(s) {
  if (s === null || s === undefined) return '';
  return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;').replace(/'/g,'&#039;');
}

function formatBookingSchedule(dateValue, timeValue, dateStyle = 'long') {
  if (!dateValue && !timeValue) {
    return 'Not set';
  }

  const parts = [];

  if (dateValue) {
    const [year, month, day] = String(dateValue).split('-').map(Number);
    if (year && month && day) {
      const localDate = new Date(year, month - 1, day);
      parts.push(localDate.toLocaleDateString('en-PH', { dateStyle }));
    } else {
      parts.push(String(dateValue));
    }
  }

  if (timeValue) {
    const localTime = new Date(`2000-01-01T${String(timeValue).slice(0, 8)}`);
    if (!Number.isNaN(localTime.getTime())) {
      parts.push(localTime.toLocaleTimeString('en-PH', { timeStyle: 'short' }));
    } else {
      parts.push(String(timeValue));
    }
  }

  return parts.join(' at ');
}

function renderCustomerAmount(booking) {
  const totalAmount = Number(booking.total_amount || 0);
  const discountPercent = Number(booking.discount_percent || 0);
  const finalAmount = Number(booking.final_amount || 0);

  if (discountPercent > 0 && finalAmount > 0) {
    return `${formatCurrency(finalAmount)} <small style="color:var(--muted)">(${discountPercent}% discount from ${formatCurrency(totalAmount)})</small>`;
  }

  if (totalAmount > 0) {
    return formatCurrency(totalAmount);
  }

  return 'To be quoted';
}

